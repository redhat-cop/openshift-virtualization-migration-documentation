#!/usr/bin/env bash
# Render inventory.yml from environment variables (no secrets in git).
# On AAP 2.5+, prefer AAP_TOKEN (gateway) over username/password for seed.
set -euo pipefail

: "${AAP_URL:?}"
: "${OCP_API:?}"
: "${VMWARE_HOST:?}"
: "${VMWARE_USER:?}"
: "${VMWARE_PASSWORD:?}"

INV_AAP_HOST="${INV_AAP_HOST:-aap-instance}"
INV_SOURCE_HOST="${INV_SOURCE_HOST:-esxi-lab}"
INV_CLUSTER_HOST="${INV_CLUSTER_HOST:-ocp-lab}"
VMWARE_SDK_PATH="${VMWARE_SDK_PATH:-/sdk}"
TARGET_NAMESPACE="${TARGET_NAMESPACE:-vm-workloads}"
AAP_PROJECT_SCM_BRANCH="${AAP_PROJECT_SCM_BRANCH:-v2}"
AAP_PROJECT_SCM_URL="${AAP_PROJECT_SCM_URL:-https://github.com/redhat-cop/openshift_virtualization_migration.git}"
EE_IMAGE="${EE_IMAGE:-quay.io/redhat-cop/openshift-virtualization-migration-ee:latest}"
VMWARE_VALIDATE_CERTS="${VMWARE_VALIDATE_CERTS:-false}"
OCP_TOKEN="${OCP_TOKEN:-}"
AAP_TOKEN="${AAP_TOKEN:-}"

OUT="${1:-inventory.yml}"

if [[ -z "${OCP_TOKEN}" ]]; then
  echo "ERROR: OCP_TOKEN is empty. Login with oc and export OCP_TOKEN=\$(oc whoami -t)" >&2
  exit 1
fi

if [[ -z "${AAP_TOKEN}" && ( -z "${AAP_USER:-}" || -z "${AAP_PASSWORD:-}" ) ]]; then
  echo "ERROR: set AAP_TOKEN (preferred on AAP 2.5+) or AAP_USER+AAP_PASSWORD" >&2
  exit 1
fi

{
  cat <<EOF
---
# Generated by render-inventory.sh — do not commit secrets.
migration_aap:
  hosts:
    ${INV_AAP_HOST}:
      aap_hostname: ${AAP_URL}
EOF
  if [[ -n "${AAP_TOKEN}" ]]; then
    cat <<EOF
      aap_token: ${AAP_TOKEN}
EOF
  else
    cat <<EOF
      aap_username: ${AAP_USER}
      aap_password: ${AAP_PASSWORD}
EOF
  fi
  cat <<EOF
      aap_validate_certs: false
      aap_project_scm_url: ${AAP_PROJECT_SCM_URL}
      aap_project_scm_branch: ${AAP_PROJECT_SCM_BRANCH}
      aap_execution_environment: Migration Factory Execution Environment
      aap_execution_environment_image: ${EE_IMAGE}
      aap_execution_environment_pull: missing
EOF
  if [[ -n "${QUAY_USER:-}" && -n "${QUAY_PASSWORD:-}" ]]; then
    cat <<EOF
      aap_execution_environment_credential: Migration Factory Registry Credential
      aap_execution_environment_host: quay.io
      aap_execution_environment_username: ${QUAY_USER}
      aap_execution_environment_password: ${QUAY_PASSWORD}
EOF
  fi
  cat <<EOF

vm_sources:
  hosts:
    ${INV_SOURCE_HOST}:
      type: vmware
      host: ${VMWARE_HOST}
      sdk_endpoint: ${VMWARE_SDK_PATH}
      username: ${VMWARE_USER}
      password: ${VMWARE_PASSWORD}
      validate_certs: ${VMWARE_VALIDATE_CERTS}
      # MTV standalone ESXi: when launching MTV Provider, set extra var:
      # mtv_provider_provider_override:
      #   settings:
      #     sdkEndpoint: ${VMWARE_SDK_ENDPOINT_TYPE:-esxi}
EOF
  if [[ -n "${VDDK_IMAGE:-}" ]]; then
    cat <<EOF
      vddk:
        image: ${VDDK_IMAGE}
EOF
    if [[ -n "${QUAY_USER:-}" && -n "${QUAY_PASSWORD:-}" ]]; then
      cat <<EOF
        username: ${QUAY_USER}
        password: ${QUAY_PASSWORD}
EOF
    fi
  fi
  cat <<EOF

migration_clusters:
  hosts:
    ${INV_CLUSTER_HOST}:
      openshift_host: ${OCP_API}
      openshift_api_key: ${OCP_TOKEN}
      openshift_verify_ssl: false
      vm_sources:
        - ${INV_SOURCE_HOST}
      aap_hosts:
        - ${INV_AAP_HOST}
      mtv_namespace: openshift-mtv
      default_target_namespace: ${TARGET_NAMESPACE}
      configure_mtv: true
EOF
} >"${OUT}"

chmod 600 "${OUT}"
echo "Wrote ${OUT}"
